// build_layers.mjs — makes src/picture/legend-data.js from the OFFICIAL GIBS colormaps in source/legends/.
// SST: bands by the Section 5A value thresholds. Rain, snow, aerosol, NDVI: each official colour entry gets the
// band of the nearest Section 5A seed colour (CIELAB), kept in value order; the band's value range is then read
// from the official entries. Prints a summary for reports/step5.md.
import fs from 'node:fs';
import { parseColormap } from './parse_colormap.mjs';
import { rgbToLab } from '../src/picture/classify.js';

const SEED = {
  rain: [[0,123,72,1],[0,156,20,1],[53,187,0,1],[163,220,0,2],[253,202,0,3],[255,108,31,4],[255,19,19,5],[200,0,0,5],[131,0,0,6],[57,0,0,6]],
  snow: [[170,249,239,1],[134,224,238,1],[106,180,223,2],[81,126,201,3],[68,84,206,3],[77,54,220,3],[107,25,233,4],[123,9,183,5],[112,6,125,5],[63,3,54,6]],
  aerosol: [[255,251,193,1],[255,236,135,1],[255,219,101,2],[255,195,70,2],[255,163,47,3],[255,131,34,3],[255,94,26,4],[250,53,18,4],[233,24,12,5],[206,5,12,5],[171,0,14,6],[131,0,14,6]],
  ndvi: [[239,231,232,1],[225,217,213,1],[225,210,197,1],[215,196,179,2],[200,181,165,2],[180,165,149,2],[177,152,131,2],[172,141,116,3],[161,128,100,3],[167,204,76,4],[150,186,33,4],[120,173,0,4],[93,163,0,5],[83,151,0,5],[67,141,0,5],[51,131,0,5],[33,120,1,6],[18,110,1,6],[5,100,1,6],[0,90,1,6]],
};
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);

function entries(file, title) {
  const cm = parseColormap(`source/legends/${file}.xml`).find((c) => c.title === title);
  return cm.entries.filter((e) => !e.transparent && !e.nodata);
}
function bySeed(list, seed) {
  const sl = seed.map((s) => [rgbToLab(s[0], s[1], s[2]), s[3]]);
  let fixes = 0, run = 1;
  const out = list.map((e) => {
    const lab = rgbToLab(...e.rgb); let b = 1, bd = Infinity;
    for (const [l, band] of sl) { const d = dist(lab, l); if (d < bd) { bd = d; b = band; } }
    if (b < run) { fixes++; b = run; } // keep bands in value order (no band going back down)
    run = b;
    return { ...e, band: b };
  });
  return { out, fixes };
}
function byThreshold(list, th) {
  return list.map((e) => { const mid = Number.isFinite(e.hi) ? (Number.isFinite(e.lo) ? (e.lo + e.hi) / 2 : e.hi - 1e-6) : e.lo; let b = 1; th.forEach((t) => { if (mid >= t) b++; }); return { ...e, band: b }; });
}
function ranges(list, nb) {
  const r = [];
  for (let b = 1; b <= nb; b++) {
    const es = list.filter((e) => e.band === b);
    if (!es.length) { r.push(null); continue; }
    const mid = es[Math.floor(es.length / 2)];
    r.push({ lo: Math.min(...es.map((e) => e.lo)), hi: Math.max(...es.map((e) => e.hi)), swatch: mid.rgb, n: es.length });
  }
  return r;
}

const sst = byThreshold(entries('GHRSST_Sea_Surface_Temperature', 'Sea Surface Temperature'), [4.3, 6.85, 16, 17.5, 20.6, 24.1, 28.2]);
const rain = bySeed(entries('GPM_Precipitation_Rate', 'Rain Rate'), SEED.rain);
const snow = bySeed(entries('GPM_Precipitation_Rate', 'Snow Rate'), SEED.snow);
const aer = bySeed(entries('MODIS_VIIRS_AOD', 'Aerosol Optical Depth'), SEED.aerosol);
const ndvi = bySeed(entries('MODIS_NDVI', 'Vegetation Indices'), SEED.ndvi);

const pack = (list, kind) => list.map((e) => (kind ? [e.rgb[0], e.rgb[1], e.rgb[2], e.band, kind] : [e.rgb[0], e.rgb[1], e.rgb[2], e.band]));
const data = {
  temperature: { ranges: ranges(sst, 8), ramp: pack(sst) },
  rain: { ranges: ranges(rain.out, 6), ramp: pack(rain.out, 'rain'), orderFixes: rain.fixes },
  snow: { ranges: ranges(snow.out, 6), ramp: pack(snow.out, 'snow'), orderFixes: snow.fixes },
  aerosol: { ranges: ranges(aer.out, 6), ramp: pack(aer.out), orderFixes: aer.fixes },
  vegetation: { ranges: ranges(ndvi.out, 6), ramp: pack(ndvi.out), orderFixes: ndvi.fixes },
};
const header = `// legend-data.js — GENERATED by tools/build_layers.mjs from the OFFICIAL GIBS colormaps (source/legends/*.xml).
// Do not edit by hand. ramp rows = [R,G,B,band(,kind)]; ranges[band-1] = {lo, hi, swatch, n} in the layer's unit.
`;
fs.writeFileSync('src/picture/legend-data.js', header + 'export const LEGENDS = ' + JSON.stringify(data, (k, v) => (v === Infinity ? 1e9 : v === -Infinity ? -1e9 : v)) + ';\n');
for (const [k, v] of Object.entries(data)) {
  console.log(`${k}: ${v.ramp.length} official colours, order fixes ${v.orderFixes ?? '-'}`);
  v.ranges.forEach((r, i) => console.log(`  band ${i + 1}: ${r ? `${r.lo} … ${r.hi}  (${r.n} colours, swatch ${r.swatch.join(',')})` : 'EMPTY'}`));
}
